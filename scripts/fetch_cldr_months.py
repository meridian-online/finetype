#!/usr/bin/env python3
"""Regenerate the CLDR abbreviated-month table behind the
datetime.date.abbreviated_month detector in
crates/finetype-core/src/discrimination.rs.

The table holds, for each Latin-script locale the type lists (plus en-GB, whose
`Sept` the type's description names), the union of CLDR's format and
stand-alone abbreviated month names, lower-cased with the trailing full stop
removed. The data comes from the Unicode CLDR release bundled with Babel (pinned to 2.18.0, which ships CLDR 47); the
CLDR version is written into the generated block.

Run by hand when CLDR publishes a new release; the build never touches the
network - the Rust source is the checked-in output.

Usage:
    uv run --with babel==2.18.0 python3 scripts/fetch_cldr_months.py          # rewrite
    uv run --with babel==2.18.0 python3 scripts/fetch_cldr_months.py --check  # exit 1 if stale
"""
import pathlib
import sys

from babel import Locale
from babel.core import get_cldr_version

# (type locale code, Babel locale). Non-Latin locales (RU, JA, ZH) are not
# listed: the published rule only matches Latin letters.
LOCALES = [
    ("EN", "en"), ("EN-GB", "en_GB"), ("FR", "fr"), ("DE", "de"), ("ES", "es"),
    ("IT", "it"), ("PT", "pt"), ("NL", "nl"), ("SV", "sv"), ("DA", "da"),
    ("NO", "nb"), ("PL", "pl"), ("CS", "cs"),
]
TARGET = pathlib.Path(__file__).resolve().parent.parent / "crates/finetype-core/src/discrimination.rs"
BEGIN, END = "// cldr-months:begin", "// cldr-months:end"


def block() -> str:
    lines = [BEGIN, f"// Generated by scripts/fetch_cldr_months.py from Unicode CLDR {get_cldr_version()}."]
    lines.append("#[rustfmt::skip]")
    lines.append("const CLDR_ABBREVIATED_MONTHS: &[(&str, &[&str])] = &[")
    for code, babel_code in LOCALES:
        loc = Locale.parse(babel_code)
        names = set()
        for ctx in ("format", "stand-alone"):
            for name in loc.months[ctx]["abbreviated"].values():
                names.add(name.lower().rstrip("."))
        body = ", ".join('"%s"' % n for n in sorted(names))
        lines.append(f'    ("{code}", &[{body}]),')
    lines.append("];")
    lines.append(END)
    return "\n".join(lines)


def main() -> int:
    src = TARGET.read_text()
    a, b = src.index(BEGIN), src.index(END) + len(END)
    new = src[:a] + block() + src[b:]
    if "--check" in sys.argv:
        if new != src:
            print("CLDR month table is stale; rerun scripts/fetch_cldr_months.py")
            return 1
        return 0
    TARGET.write_text(new)
    return 0


if __name__ == "__main__":
    sys.exit(main())
