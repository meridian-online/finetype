#!/usr/bin/env python3
"""Fetch the SIX ISO 4217 lists and regenerate the currency_code rule in
labels/definitions_finance.yaml.

Two SIX files feed the rule:

1. list-one.xml   - the codes in current use. Every one is accepted.
2. list-three.xml - historic codes with their withdrawal date. A historic
   code is kept when it was withdrawn on or after 1999-01-01, is not in
   list one, and carries a month-precise date; it is accepted and graded
   `Noted(Withdrawn, "withdrawn YYYY-MM")` through validation_notes.historic.
   A code listed several times takes its latest withdrawal date. A code in
   both lists (a reused code) belongs to list one only.

The published enum is list one UNION the historic set. The two generated
regions of the YAML sit between `iso4217:enum` and `iso4217:historic`
begin/end marker comments; everything else in the file is left alone.

Run by hand when SIX publishes a new edition; the build never touches the
network - the YAML is the checked-in output.

Usage:
    python3 scripts/fetch_iso4217.py            # fetch + rewrite the YAML
    python3 scripts/fetch_iso4217.py --check    # exit 1 if the YAML is stale
"""
import re
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

BASE = "https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/"
LIST_ONE = BASE + "list-one.xml"
LIST_THREE = BASE + "list-three.xml"
UA = "Mozilla/5.0 (compatible; FineType taxonomy refresh)"
CUTOFF = "1999-01"
YAML = Path(__file__).resolve().parent.parent / "labels" / "definitions_finance.yaml"


def curl(url: str) -> str:
    proc = subprocess.run(
        ["curl", "-sS", "--fail", "-A", UA, url],
        capture_output=True,
        text=True,
        timeout=60,
    )
    if proc.returncode != 0:
        raise RuntimeError(f"curl failed ({proc.returncode}) for {url}: {proc.stderr.strip()}")
    return proc.stdout


def build():
    one = {
        e.findtext("Ccy")
        for e in ET.fromstring(curl(LIST_ONE).encode()).iter("CcyNtry")
        if e.findtext("Ccy")
    }
    withdrawn = {}
    for e in ET.fromstring(curl(LIST_THREE).encode()).iter("HstrcCcyNtry"):
        code, when = e.findtext("Ccy"), (e.findtext("WthdrwlDt") or "").strip()
        # Month-precise dates only; the year-only and range forms are all
        # pre-1999 and fall below the cutoff anyway.
        if code and re.fullmatch(r"\d{4}-\d{2}", when):
            withdrawn[code] = max(withdrawn.get(code, ""), when)
    historic = {c: d for c, d in withdrawn.items() if c not in one and d >= CUTOFF}
    if not one or not historic:
        raise RuntimeError("empty list one or historic set; refusing to rewrite")
    return sorted(one), dict(sorted(historic.items()))


def wrap(codes, indent):
    lines, cur = [], ""
    for c in codes:
        piece = c + ","
        if len(indent) + len(cur) + len(piece) + 1 > 76 and cur:
            lines.append(indent + cur.rstrip())
            cur = ""
        cur += piece + " "
    lines.append(indent + cur.rstrip())
    return "\n".join(lines)


def render(src, one, historic):
    allcodes = sorted(set(one) | set(historic))
    enum_body = wrap(allcodes, "      ").rstrip(",")
    enum_block = (
        "    # iso4217:enum begin (generated by scripts/fetch_iso4217.py)\n"
        f"    enum: [\n{enum_body}]\n"
        "    # iso4217:enum end"
    )
    hist_lines = "\n".join(
        f'      - {{ value: "{c}", until: "{d}" }}' for c, d in historic.items()
    )
    hist_block = (
        "    # iso4217:historic begin (generated by scripts/fetch_iso4217.py)\n"
        f"    historic:\n{hist_lines}\n"
        "    # iso4217:historic end"
    )
    src, n1 = re.subn(
        r"    # iso4217:enum begin.*?# iso4217:enum end", lambda m: enum_block, src, flags=re.S
    )
    src, n2 = re.subn(
        r"    # iso4217:historic begin.*?# iso4217:historic end",
        lambda m: hist_block,
        src,
        flags=re.S,
    )
    if (n1, n2) != (1, 1):
        raise RuntimeError("marker comments not found in definitions_finance.yaml")
    return src


def main():
    one, historic = build()
    old = YAML.read_text()
    new = render(old, one, historic)
    if "--check" in sys.argv:
        if new != old:
            print("currency_code rule is stale; run scripts/fetch_iso4217.py")
            sys.exit(1)
        return
    YAML.write_text(new)
    print(f"list one: {len(one)} codes; historic: {len(historic)} codes")


if __name__ == "__main__":
    main()
