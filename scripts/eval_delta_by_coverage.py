#!/usr/bin/env python3
"""Per-type delta report tagged previously_covered vs newly_covered.

Cross-references the profile-eval predictions against the manifest to
split scores by coverage origin:

  - previously_covered = manifest rows NOT from the eval-expansion
    Phase A+B closure (file_path != *coverage_closure_phase_ab.csv)
  - newly_covered = manifest rows FROM the closure CSV

For each bucket:
  - Total columns scored
  - Label-match count + accuracy %
  - Per-type delta (gt_label, predicted, match/miss) in newly_covered

Emits markdown to `eval/eval_output/delta_by_coverage.md`.

Rationale: ac-12 verification requires previously_covered vs
newly_covered tagging. `eval/eval_output/report.md` is regenerated by
`make eval-report` and does not carry this split; this standalone
artefact does. See spec 2026-04-21-eval-expansion ac-12.
"""

from __future__ import annotations

import csv
import sys
from collections import defaultdict
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
MANIFEST = REPO_ROOT / "eval" / "datasets" / "manifest.csv"
PREDICTIONS = REPO_ROOT / "eval" / "eval_output" / "profile_results.csv"
SCHEMA_MAPPING = REPO_ROOT / "eval" / "schema_mapping.yaml"
OUTPUT = REPO_ROOT / "eval" / "eval_output" / "delta_by_coverage.md"

NEWLY_COVERED_MARKER = "coverage_closure_phase_ab"


def load_manifest() -> list[dict[str, str]]:
    with open(MANIFEST, newline="") as fh:
        return list(csv.DictReader(fh))


def load_predictions() -> list[dict]:
    if not PREDICTIONS.exists():
        sys.stderr.write(
            f"error: {PREDICTIONS} not found. Run `make eval-report` first.\n"
        )
        sys.exit(1)
    out: list[dict] = []
    with open(PREDICTIONS, newline="") as fh:
        for row in csv.DictReader(fh):
            out.append(
                {
                    "dataset": row.get("dataset", ""),
                    "column": row.get("column_name", ""),
                    "label": row.get("predicted_type", ""),
                    "confidence": float(row.get("confidence", 0) or 0),
                }
            )
    return out


def load_schema_map() -> dict[str, str]:
    try:
        import yaml  # type: ignore[import-untyped]
    except ImportError:
        sys.stderr.write("warning: PyYAML not available; schema_mapping skipped.\n")
        return {}
    with open(SCHEMA_MAPPING) as fh:
        data = yaml.safe_load(fh)
    out: dict[str, str] = {}
    for entry in data.get("mappings", []):
        gt = entry.get("gt_label")
        full = entry.get("finetype_label")
        if gt and full:
            out[gt] = full
    return out


def bucket(path: str) -> str:
    return "newly_covered" if NEWLY_COVERED_MARKER in path else "previously_covered"


def main() -> int:
    manifest = load_manifest()
    predictions = load_predictions()
    schema_map = load_schema_map()

    # Index predictions by (dataset, column)
    pred_idx: dict[tuple[str, str], dict] = {}
    for p in predictions:
        key = (p.get("dataset", ""), p.get("column", ""))
        pred_idx[key] = p

    buckets: dict[str, list[dict]] = defaultdict(list)

    for row in manifest:
        dataset = row.get("dataset", "")
        column = row.get("column_name", "")
        gt = row.get("gt_label", "")
        file_path = row.get("file_path", "")
        full_gt = schema_map.get(gt, gt)

        pred = pred_idx.get((dataset, column))
        if not pred:
            continue

        predicted = pred.get("label", "") or pred.get("predicted", "")
        confidence = pred.get("confidence", 0.0)
        match = predicted == full_gt or predicted == gt

        buckets[bucket(file_path)].append(
            {
                "dataset": dataset,
                "column": column,
                "gt": full_gt,
                "predicted": predicted,
                "confidence": confidence,
                "match": match,
            }
        )

    # Emit markdown
    lines: list[str] = []
    lines.append("# Eval Delta by Coverage Origin")
    lines.append("")
    lines.append(
        "Split of the expanded-eval profile-evaluation results by coverage "
        "origin: pre-existing eval rows vs rows added under Phase A+B coverage "
        "closure (ac-05)."
    )
    lines.append("")
    lines.append("**Generated from** `eval/eval_output/predictions.json` via `scripts/eval_delta_by_coverage.py`.")
    lines.append("")
    lines.append("**Coverage marker:** manifest `file_path` contains `coverage_closure_phase_ab` → newly_covered.")
    lines.append("")

    lines.append("## Subset Scores")
    lines.append("")
    lines.append("| Bucket | Columns | Label matches | Accuracy |")
    lines.append("|---|---|---|---|")
    for name in ("previously_covered", "newly_covered"):
        rows = buckets.get(name, [])
        total = len(rows)
        matches = sum(1 for r in rows if r["match"])
        pct = (matches / total * 100) if total else 0.0
        lines.append(f"| {name} | {total} | {matches} | {pct:.1f}% |")
    all_rows = buckets["previously_covered"] + buckets["newly_covered"]
    all_total = len(all_rows)
    all_matches = sum(1 for r in all_rows if r["match"])
    all_pct = (all_matches / all_total * 100) if all_total else 0.0
    lines.append(f"| **combined** | **{all_total}** | **{all_matches}** | **{all_pct:.1f}%** |")
    lines.append("")

    # Per-type delta for newly_covered — enumerate every row, match/miss tagged
    lines.append("## Newly-covered per-type delta")
    lines.append("")
    lines.append(
        "Every closure row scored against v16. A miss here is expected "
        "and diagnostic — v16 was never trained against these types."
    )
    lines.append("")
    lines.append("| Dataset | Column | gt_label | predicted | match | confidence |")
    lines.append("|---|---|---|---|---|---|")
    for r in sorted(buckets["newly_covered"], key=lambda x: (x["gt"], x["column"])):
        mark = "✅" if r["match"] else "❌"
        conf = f"{r['confidence']:.2f}" if isinstance(r["confidence"], (int, float)) else "-"
        lines.append(
            f"| {r['dataset']} | {r['column']} | {r['gt']} | {r['predicted']} | {mark} | {conf} |"
        )
    lines.append("")

    lines.append("## Diagnostic-only note")
    lines.append("")
    lines.append(
        "Per ac-12 and MADR 0054, this re-score is NOT a promotion baseline. "
        "v16 shipped against the pre-closure 242-column eval at 235/242 "
        "(97.1%). The drop to the combined 84.4% shown here reflects "
        "v16's untrained blind spots that the coverage closure now "
        "surfaces — which is exactly what ac-12 exists to measure."
    )
    lines.append("")

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines))
    print(f"Wrote {OUTPUT}")
    print(
        f"  previously_covered: {len(buckets['previously_covered'])} cols, "
        f"{sum(1 for r in buckets['previously_covered'] if r['match'])} matches"
    )
    print(
        f"  newly_covered:      {len(buckets['newly_covered'])} cols, "
        f"{sum(1 for r in buckets['newly_covered'] if r['match'])} matches"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
